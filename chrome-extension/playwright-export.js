/**
 * playwright-export.js — render a generated suite as a Playwright spec file.
 *
 * Grounding proves a test names real UI; running it proves the steps work. This
 * turns each test into Playwright code the team can run in CI. Locators prefer a
 * stable selector from the crawl (#id, data-testid), else Playwright's role /
 * label / text locators. Steps the parser could not automate are kept as
 * `// MANUAL:` comments, and a test with no automatable assertion is emitted as
 * `test.fixme` with the reason, so it can never pass green without checking
 * anything.
 *
 * Pure: suite in, source text out.
 */
(function () {

const TS = (typeof TestSteps !== 'undefined' && TestSteps)
  || (typeof self !== 'undefined' && self.TestSteps)
  || (typeof require === 'function' ? require('./test-steps.js') : null);

const lit = (s) => JSON.stringify(String(s == null ? '' : s));
/** "/api/orders/:id" or "/api/orders/{id}" → an anchored regex source for the pathname. */
const pathRegex = (path) => '^' + String(path).split('/').map(seg => (/^(:\w+|\{[^}]+\})$/.test(seg)
  ? '[^/]+' : seg.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'))).join('/') + '$';
const ident = (s) => String(s || 'value').toUpperCase().replace(/[^A-Z0-9]+/g, '_').replace(/^_|_$/g, '') || 'VALUE';

function control(target, sel) {
  return sel.has(target.toLowerCase()) ? `page.locator(${lit(sel.get(target.toLowerCase()))})` : `control(page, ${lit(target)})`;
}
function field(target, sel) {
  return sel.has(target.toLowerCase()) ? `page.locator(${lit(sel.get(target.toLowerCase()))})` : `field(page, ${lit(target)})`;
}

function renderTest(tc, sel) {
  const p = TS.parseTestCase(tc);
  const name = `${tc.id ? tc.id + ' ' : ''}${tc.title || 'Untitled test'}`;
  const body = [];
  if (p.automation === 'none') {
    body.push(`    test.fixme(true, ${lit('No automatable assertion: ' + (p.manualCheck || 'expected result missing'))});`);
  }
  if (tc.preconditions) body.push(`    // Preconditions: ${String(tc.preconditions).replace(/\n/g, ' ')}`);
  p.assertions.filter(a => a.kind === 'api').forEach((a, i) => {
    body.push(`    const api${i} = page.waitForResponse(r => r.request().method() === ${lit(a.method)} && new RegExp(${lit(pathRegex(a.path))}).test(new URL(r.url()).pathname));`);
  });
  if (p.startUrl) body.push(`    await page.goto(${lit(p.startUrl)});`);
  for (const a of p.actions) {
    switch (a.kind) {
      case 'goto': body.push(`    await page.goto(${lit(a.url)});`); break;
      case 'click': body.push(`    await ${control(a.target, sel)}.click();`); break;
      case 'fill': {
        const value = a.value != null ? lit(a.value)
          : `process.env.${ident(a.target)} ?? ${lit('TODO: ' + (a.describe || a.target))}`;
        body.push(`    await ${field(a.target, sel)}.fill(${value});${a.value == null ? ' // test data: ' + (a.describe || '') : ''}`);
        break;
      }
      case 'select': body.push(`    await ${field(a.target, sel)}.selectOption({ label: ${lit(a.value)} });`); break;
      case 'check': body.push(`    await ${field(a.target, sel)}.check();`); break;
      case 'uncheck': body.push(`    await ${field(a.target, sel)}.uncheck();`); break;
      default: body.push(`    // MANUAL: ${a.text.replace(/\n/g, ' ')}`);
    }
  }
  let apiIdx = 0;
  for (const a of p.assertions) {
    if (a.kind === 'api') {
      const v = `api${apiIdx++}`;
      body.push(a.status ? `    expect((await ${v}).status()).toBe(${a.status});` : `    await ${v};`);
    } else if (a.kind === 'url') {
      body.push(`    await expect(page).toHaveURL(new RegExp(${lit(a.path.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'))}));`);
    } else if (a.kind === 'text') {
      body.push(`    await expect(page.getByText(${lit(a.value)}).first()).toBeVisible();`);
    }
  }
  body.push(`    // Expected: ${String(tc.expected_result || tc.expectedResult || '').replace(/\n/g, ' ')}`);
  const tags = [tc.category, tc.priority].filter(Boolean).map(t => `@${String(t).toLowerCase()}`).join(' ');
  return [`  test(${lit(name + (tags ? ' ' + tags : ''))}, async ({ page }) => {`, ...body, '  });'].join('\n');
}

/**
 * @returns {{ filename, source, stats: {full, partial, none} }}
 */
function exportPlaywrightSpec(testCases, { ticketKey = 'QATALYST', summary = '', knowledgeGraph = null } = {}) {
  const sel = TS.selectorIndex(knowledgeGraph);
  const stats = { full: 0, partial: 0, none: 0 };
  const tests = (testCases || []).map(tc => {
    stats[TS.parseTestCase(tc).automation]++;
    return renderTest(tc, sel);
  });
  const source = [
    `// Generated by QAtalyst from ${ticketKey}${summary ? ': ' + summary.replace(/\n/g, ' ') : ''}.`,
    `// ${stats.full} fully automated, ${stats.partial} with MANUAL steps or TODO test data, ${stats.none} test.fixme (no automatable assertion).`,
    '// Fill TODO values via environment variables (e.g. EMAIL=... npx playwright test), then review each MANUAL line.',
    "const { test, expect } = require('@playwright/test');",
    '',
    'const control = (page, name) => page.getByRole(\'button\', { name, exact: true })',
    '  .or(page.getByRole(\'link\', { name, exact: true }))',
    '  .or(page.getByRole(\'tab\', { name, exact: true }))',
    '  .or(page.getByRole(\'menuitem\', { name, exact: true })).first();',
    'const field = (page, name) => page.getByLabel(name).or(page.getByPlaceholder(name)).first();',
    '',
    `test.describe(${lit(ticketKey + (summary ? ': ' + summary : ''))}, () => {`,
    tests.join('\n\n'),
    '});',
    ''
  ].join('\n');
  return { filename: `${String(ticketKey).replace(/[^\w.-]+/g, '_')}.spec.js`, source, stats };
}

const api = { exportPlaywrightSpec };
if (typeof module !== 'undefined' && module.exports) module.exports = api;
if (typeof self !== 'undefined') self.PlaywrightExport = api;
})();
